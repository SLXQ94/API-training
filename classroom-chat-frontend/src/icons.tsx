/** message status next to the time: a clock while sending, a tick once the server has it */
export function MessageStatus({ status }: { status: 'sent' | 'sending' | 'failed' }) {
  if (status === 'sending') {
    return (
      <svg viewBox="0 0 16 15" width="16" height="15" className="status-icon" aria-label="Sending">
        <circle cx="8" cy="7.5" r="5.2" fill="none" stroke="currentColor" strokeWidth="1.3" />
        <path d="M8 4.6v3.3l2.1 1.3" fill="none" stroke="currentColor" strokeWidth="1.3" strokeLinecap="round" />
      </svg>
    );
  }
  if (status === 'failed') return null;
  return (
    <svg viewBox="0 0 16 11" width="16" height="11" className="status-icon" aria-label="Sent">
      <path d="M2 6.1 5.1 9.2 12.3 1.3" fill="none" stroke="currentColor" strokeWidth="1.5" strokeLinecap="round" strokeLinejoin="round" />
    </svg>
  );
}

