/**
 * A person is a coloured disc with their initial (colour is stable per person); the class group is a silhouette.
 * `id` picks the colour, `name` supplies the letter.
 */
export function Avatar({ group = false, size = 49, id, name }: { group?: boolean; size?: number; id?: string; name?: string }) {
  if (!group && name) {
    const initial = Array.from(name.trim())[0]?.toLocaleUpperCase() ?? '?';
    return (
      <span
        className="avatar initial"
        style={{ width: size, height: size, fontSize: Math.round(size * 0.44), '--h': hueOf(id ?? name) } as CSSProperties}
        aria-hidden="true"
      >
        {initial}
      </span>
    );
  }
  return (
    <span className="avatar" style={{ width: size, height: size }}>
      <svg viewBox="0 0 212 212" width={size} height={size} aria-hidden="true">
        <clipPath id="avatar-clip">
          <circle cx="106" cy="106" r="106" />
        </clipPath>
        <circle cx="106" cy="106" r="106" className="avatar-bg" />
        <g className="avatar-fg" clipPath="url(#avatar-clip)">
          {group ? (
            <>
              <circle cx="106" cy="80" r="26" />
              <path d="M58 150c3-26 22-38 48-38s45 12 48 38z" />
              <circle cx="63" cy="92" r="19" opacity=".85" />
              <circle cx="149" cy="92" r="19" opacity=".85" />
              <path d="M24 148c2-19 16-28 34-28 4 0 8 .5 11 1.6-8 6-12 14-14 26.4z" opacity=".85" />
              <path d="M188 148c-2-19-16-28-34-28-4 0-8 .5-11 1.6 8 6 12 14 14 26.4z" opacity=".85" />
            </>
          ) : (
            <>
              <circle cx="106" cy="86" r="36" />
              <path d="M36 190c4-42 36-62 70-62s66 20 70 62a106 106 0 0 1-140 0z" />
            </>
          )}
        </g>
      </svg>
    </span>
  );
}
